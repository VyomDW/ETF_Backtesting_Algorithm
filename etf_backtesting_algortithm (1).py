    zscore = features["zscore"].values
    spread = features["spread"].values
    dates = features.index

    is_extreme = np.abs(zscore) > ENTRY_THRESHOLD
    newly_extreme_raw = is_extreme & ~np.roll(is_extreme, 1)
    newly_extreme_raw[0] = False

    event_indices = []
    last_event_idx = -COOLDOWN_DAYS
    for idx in np.where(newly_extreme_raw)[0]:
        if idx - last_event_idx >= COOLDOWN_DAYS:
            event_indices.append(idx)
            last_event_idx = idx

    events = []
    prior_outcomes = []

    for idx in event_indices:
        if idx + LOOKAHEAD_DAYS >= len(features):
            continue
        entry_zscore = zscore[idx]
        entry_spread = spread[idx]
        future_zscore = zscore[idx + 1: idx + 1 + LOOKAHEAD_DAYS]
