"""
PHASE 4 (v2): Probability-weighted position sizing.

Instead of a hard filter (only trade if predicted label == 1), we take EVERY
trade, but size each position proportionally to the model's predicted
probability of success. A trade the model is 80% confident about gets a
bigger position than one it's only 40% confident about -- but we never fully
throw away a trade the way the hard filter did, which was cutting frequency
nearly in half and hurting the Sharpe ratio.

position_size_i = BASE_SIZE * predicted_probability_i (with a floor so we're
never betting literally zero on a trade).

Run this locally: pip install pandas numpy pykalman statsmodels scikit-learn yfinance matplotlib
"""

import pandas as pd
import numpy as np
from pykalman import KalmanFilter
import statsmodels.api as sm
from sklearn.linear_model import LogisticRegression
import yfinance as yf
import matplotlib.pyplot as plt

ENTRY_THRESHOLD = 2.0
STOP_LOSS_THRESHOLD = 3.5
REVERT_THRESHOLD = 0.5
COOLDOWN_DAYS = 15
ROLL_WINDOW = 60
N_PAIRS_TO_POOL = 15
SLIPPAGE_ROUND_TRIP = 0.0008
BORROW_RATE_ANNUAL = 0.01
BASE_POSITION_SIZE = 0.05
MIN_PROB_FLOOR = 0.15  # never size below 15% of base, even for low-confidence trades

