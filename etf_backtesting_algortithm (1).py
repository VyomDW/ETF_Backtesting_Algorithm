majority_class = y_train.mode()[0]
majority_baseline_acc = (y_test == majority_class).mean()

np.random.seed(42)
random_preds = np.random.choice([0, 1], size=len(y_test))
random_baseline_acc = (y_test == random_preds).mean()

print(f"\n{'=' * 60}")
print("BASELINES")
print(f"{'=' * 60}")
