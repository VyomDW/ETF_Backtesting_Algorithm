def ou_half_life(spread):
    """
    Fits the discretized OU process: spread_t - spread_(t-1) = theta*(mu - spread_(t-1)) + noise
    This is just a linear regression of the day-to-day CHANGE in spread against
    the PREVIOUS day's spread level -- if the spread is mean-reverting, this
    regression's slope will be negative (the further from the mean, the bigger
    the pull back).

    Returns: half-life in trading days (how long it takes to revert halfway
    back to the mean, on average).
    """
    spread = spread.dropna()
    spread_lag = spread.shift(1).dropna()
    spread_diff = spread.diff().dropna()

    # align indices
    spread_lag = spread_lag.loc[spread_diff.index]

    X = sm.add_constant(spread_lag)
    model = sm.OLS(spread_diff, X).fit()

    theta = -model.params.iloc[1]  # mean-reversion speed
    half_life = np.log(2) / theta if theta > 0 else np.nan

    return half_life, theta, model


