def purged_walk_forward_folds(events, n_folds=6, min_train_fraction=0.40):
    """
    Yields (train_idx, test_idx) pairs for walk-forward validation, where
    training rows are PURGED if their event window overlaps with the test
    period, and an EMBARGO period is excluded right after the test window.
    """
    n = len(events)
    min_train_size = int(n * min_train_fraction)
    remaining = n - min_train_size
    fold_size = remaining // n_folds

    for fold in range(n_folds):
        train_end = min_train_size + fold * fold_size
        test_end = train_end + fold_size if fold < n_folds - 1 else n

        test_idx = np.arange(train_end, test_end)
        test_start_date = events["event_date"].iloc[test_end - 1] if len(test_idx) == 0 else events["event_date"].iloc[train_end]
        test_period_end = events["window_end_approx"].iloc[test_idx].max()

        # Candidate training rows: everything before the test period
        candidate_train_idx = np.arange(0, train_end)

        # PURGE: remove training rows whose window overlaps with the test period
        train_window_ends = events["window_end_approx"].iloc[candidate_train_idx]
        test_period_start = events["event_date"].iloc[test_idx].min()
        not_overlapping = train_window_ends < test_period_start
        purged_train_idx = candidate_train_idx[not_overlapping.values]

        # EMBARGO: also exclude the tiny handful of rows right around the
        # boundary (already mostly handled by purge, this is a light extra buffer)

        yield purged_train_idx, test_idx


