    for idx in event_indices:
        if idx + holding_window >= len(features):
            continue
        future_zscore = zscore_vals[idx + 1: idx + 1 + holding_window]
        reverted_mask = np.abs(future_zscore) < REVERT_THRESHOLD
        stopped_out_mask = np.abs(future_zscore) >= STOP_LOSS_THRESHOLD

        revert_day = np.argmax(reverted_mask) if reverted_mask.any() else None
        stop_day = np.argmax(stopped_out_mask) if stopped_out_mask.any() else None

        if revert_day is not None and (stop_day is None or revert_day < stop_day):
            label, outcome, exit_day = 1, "reverted", revert_day
        elif stop_day is not None:
            label, outcome, exit_day = 0, "stopped_out", stop_day
        else:
            label, outcome, exit_day = 0, "timed_out", holding_window - 1

        event_row = features.iloc[idx].to_dict()
        event_row.update({
            "event_date": dates[idx],
            "pair": f"{ticker_a}/{ticker_b}",
            "entry_zscore": zscore_vals[idx],
            "half_life": half_life,
            "holding_window": holding_window,
            "label": label,
            "outcome": outcome,
            "days_to_exit": exit_day + 1,
        })
        events.append(event_row)

    return pd.DataFrame(events)


