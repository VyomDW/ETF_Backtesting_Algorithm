events = events.sort_values("event_date").reset_index(drop=True)
FEATURE_COLS = [
    "abs_entry_zscore",
    "volatility_a",
    "volatility_b",
    "volatility_ratio",
    "rolling_correlation",
    "corr_trend_20d",
    "zscore_momentum_5d",
    "spread_vol_trend_20d",
    "days_since_crossing",
    "pair_historical_reversion_rate",
]

X = events[FEATURE_COLS]
y = events["reverted"]

# ---------------------------------------------------------
# Walk-forward folds
# ---------------------------------------------------------
# Start training on the first 40% of events, then walk forward in chunks,
# testing on the next chunk each time, growing the training set as we go.

N = len(events)
MIN_TRAIN_FRACTION = 0.40
N_FOLDS = 6

min_train_size = int(N * MIN_TRAIN_FRACTION)
remaining = N - min_train_size
fold_size = remaining // N_FOLDS

print(f"\nTotal events: {N}")
print(f"Initial training size: {min_train_size}, {N_FOLDS} folds of ~{fold_size} test events each")

fold_results = []

for fold in range(N_FOLDS):
    train_end = min_train_size + fold * fold_size
    test_end = train_end + fold_size if fold < N_FOLDS - 1 else N

    X_train, y_train = X.iloc[:train_end], y.iloc[:train_end]
    X_test, y_test = X.iloc[train_end:test_end], y.iloc[train_end:test_end]

    if len(X_test) == 0 or y_test.nunique() < 1:
        continue

    train_reversion_rate = y_train.mean()
    test_reversion_rate = y_test.mean()

    # Baseline: always predict test period's true majority (best-case naive baseline)
    naive_baseline_acc = max(test_reversion_rate, 1 - test_reversion_rate)

    fold_row = {
        "fold": fold + 1,
        "test_start_date": events["event_date"].iloc[train_end].date(),
        "n_train": len(X_train),
        "n_test": len(X_test),
        "train_reversion_rate": round(train_reversion_rate * 100, 1),
        "test_reversion_rate": round(test_reversion_rate * 100, 1),
        "naive_baseline_acc": round(naive_baseline_acc, 3),
    }

    for name, model in [
        ("logreg", LogisticRegression(max_iter=1000, class_weight="balanced")),
        ("rf", RandomForestClassifier(n_estimators=200, max_depth=4,
                                       min_samples_leaf=10, class_weight="balanced",
                                       random_state=42)),
    ]:
        model.fit(X_train, y_train)
        preds = model.predict(X_test)
        fold_row[f"{name}_acc"] = round(accuracy_score(y_test, preds), 3)
        fold_row[f"{name}_f1"] = round(f1_score(y_test, preds, zero_division=0), 3)

    fold_results.append(fold_row)

results_df = pd.DataFrame(fold_results)
results_df.to_csv("walk_forward_results_v2.csv", index=False)

