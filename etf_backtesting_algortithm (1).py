print("AND high historical stability -- that's your final pair for step 3.")

"""
STEP 3: Engineer spread features for JPM/BAC.

Goal: turn the raw price series into features that describe "how unusual is
the current divergence" -- these are what the classifier will eventually
learn from.

We use the LOG spread (log(JPM) - log(BAC)) instead of the raw price ratio.
Why: log spreads behave more symmetrically (a 10% move up and a 10% move down
look the same size in log-space, which isn't true for a raw ratio) and this
is the standard convention in pairs trading literature.

Features built here:
  - spread: log(JPM) - log(BAC)
  - rolling mean / rolling std of the spread (60-day window)
  - z-score: how many standard deviations the spread is from its recent mean
    (this is the core "how extreme is this divergence" signal)
  - rolling volatility of each individual stock (20-day)
  - rolling correlation between JPM and BAC (60-day)
  - days_since_crossing: how many trading days since the spread last crossed
    its own rolling mean (a long stretch without crossing back = warning sign)

Run this locally: pip install pandas numpy matplotlib
"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

print("Loading universe price data...")
prices = pd.read_csv("universe_prices.csv", index_col="Date", parse_dates=True)

pair = prices[["JPM", "BAC"]].copy()

# ---------------------------------------------------------
# Core spread + z-score
# ---------------------------------------------------------

pair["log_jpm"] = np.log(pair["JPM"])
pair["log_bac"] = np.log(pair["BAC"])
pair["spread"] = pair["log_jpm"] - pair["log_bac"]

ROLL_WINDOW = 60  # ~3 trading months

pair["spread_mean"] = pair["spread"].rolling(ROLL_WINDOW).mean()
pair["spread_std"] = pair["spread"].rolling(ROLL_WINDOW).std()
pair["zscore"] = (pair["spread"] - pair["spread_mean"]) / pair["spread_std"]

# ---------------------------------------------------------
# Individual stock volatility (20-day rolling std of daily returns)
# ---------------------------------------------------------

VOL_WINDOW = 20

pair["jpm_return"] = pair["JPM"].pct_change()
pair["bac_return"] = pair["BAC"].pct_change()

pair["jpm_volatility"] = pair["jpm_return"].rolling(VOL_WINDOW).std()
pair["bac_volatility"] = pair["bac_return"].rolling(VOL_WINDOW).std()

# ---------------------------------------------------------
# Rolling correlation between the two stocks' returns
# ---------------------------------------------------------

CORR_WINDOW = 60

pair["rolling_correlation"] = pair["jpm_return"].rolling(CORR_WINDOW).corr(
    pair["bac_return"]
)

# ---------------------------------------------------------
# Days since the spread last crossed its own rolling mean
# A long stretch without crossing = the spread has been stuck on one side,
# which is a warning sign that it might not be reverting normally.
# ---------------------------------------------------------

above_mean = (pair["spread"] > pair["spread_mean"]).astype(int)
crossing = above_mean.diff().fillna(0) != 0  # True on days the sign flips

days_since_crossing = []
counter = 0
for crossed in crossing:
    if crossed:
        counter = 0
    else:
        counter += 1
    days_since_crossing.append(counter)

pair["days_since_crossing"] = days_since_crossing

# ---------------------------------------------------------
# Clean up and save
# ---------------------------------------------------------

features = pair.dropna()
features.to_csv("jpm_bac_features.csv")

print(f"\nFeature table shape: {features.shape[0]} rows x {features.shape[1]} columns")
print("\nColumns:", list(features.columns))
print("\nSample rows:")
print(features[["spread", "zscore", "jpm_volatility", "bac_volatility",
                 "rolling_correlation", "days_since_crossing"]].tail(10))

print(f"\nZ-score stats:")
print(features["zscore"].describe())

# ---------------------------------------------------------
# Visualize
# ---------------------------------------------------------

fig, axes = plt.subplots(4, 1, figsize=(11, 12), sharex=True)

axes[0].plot(features.index, features["spread"], label="spread")
axes[0].plot(features.index, features["spread_mean"], color="red",
             linestyle="--", label="rolling mean")
axes[0].set_title("JPM/BAC log spread")
axes[0].legend()

axes[1].plot(features.index, features["zscore"], color="purple")
axes[1].axhline(2, color="red", linestyle="--", alpha=0.6, label="+/- 2 std")
axes[1].axhline(-2, color="red", linestyle="--", alpha=0.6)
axes[1].axhline(0, color="black", linewidth=0.8)
axes[1].set_title("Z-score (how extreme is the current divergence)")
axes[1].legend()

axes[2].plot(features.index, features["rolling_correlation"], color="green")
axes[2].set_title("Rolling 60-day correlation between JPM and BAC returns")

axes[3].plot(features.index, features["days_since_crossing"], color="orange")
axes[3].set_title("Days since spread last crossed its rolling mean")

plt.tight_layout()
plt.savefig("jpm_bac_features.png", dpi=120)
print("\nSaved plot to jpm_bac_features.png")
plt.show()

"""
STEP 4: Label historical divergence events.

An "event" = a moment the z-score crosses beyond +/-2 (the spread becomes
unusually stretched). For each event, we look FORWARD up to N trading days
and ask: did the z-score make it back close to 0 (reverted), or did it stay
stretched / keep diverging the whole window (broke down)?

This label is what the classifier in step 5 will learn to predict.

Two parameters matter a lot here and are worth being deliberate about:
  ENTRY_THRESHOLD = how extreme the z-score must get to count as an "event"
  LOOKAHEAD_DAYS  = how many days we give it to revert before calling it a break
  REVERT_THRESHOLD = how close to 0 counts as "reverted" (doesn't need to be exact)

Run this locally: pip install pandas numpy matplotlib
"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

print("Loading feature data...")
features = pd.read_csv("jpm_bac_features.csv", index_col="Date", parse_dates=True)

ENTRY_THRESHOLD = 2.0     # z-score must exceed this (either direction) to count as an event
LOOKAHEAD_DAYS = 20       # ~1 trading month to revert
REVERT_THRESHOLD = 0.5    # z-score must come back within this band to count as "reverted"

zscore = features["zscore"].values
dates = features.index

# ---------------------------------------------------------
# Find divergence events: a day where |z| crosses ABOVE the threshold
# (i.e. the previous day was inside the threshold, today is outside it)
# This avoids counting every single day of an extended divergence as a
# separate event -- we only want the moment it FIRST becomes extreme.
# ---------------------------------------------------------

is_extreme = np.abs(zscore) > ENTRY_THRESHOLD
newly_extreme = is_extreme & ~np.roll(is_extreme, 1)
newly_extreme[0] = False  # ignore the first row (no prior day to compare)

event_indices = np.where(newly_extreme)[0]
print(f"\nFound {len(event_indices)} divergence events (|z| crossing above {ENTRY_THRESHOLD})")

# ---------------------------------------------------------
# For each event, look forward and label revert vs break
# ---------------------------------------------------------

events = []

for idx in event_indices:
    if idx + LOOKAHEAD_DAYS >= len(features):
        continue  # not enough future data to evaluate this event, skip

    entry_zscore = zscore[idx]
    future_window = zscore[idx + 1: idx + 1 + LOOKAHEAD_DAYS]

    # Reverted if the z-score comes back within the revert band at ANY point
    # during the lookahead window
    reverted = np.any(np.abs(future_window) < REVERT_THRESHOLD)

    # Also record how many days it took to revert (NaN if it never did)
    if reverted:
        days_to_revert = np.argmax(np.abs(future_window) < REVERT_THRESHOLD) + 1
    else:
        days_to_revert = np.nan

    event_row = features.iloc[idx].to_dict()
    event_row.update({
        "event_date": dates[idx],
        "entry_zscore": entry_zscore,
        "reverted": int(reverted),
        "days_to_revert": days_to_revert,
    })
    events.append(event_row)

events_df = pd.DataFrame(events).set_index("event_date")
events_df.to_csv("jpm_bac_labeled_events.csv")

# ---------------------------------------------------------
# Summary
# ---------------------------------------------------------

print(f"\nLabeled {len(events_df)} events (skipped events too close to the end of the data)")
print(f"\nClass balance:")
print(events_df["reverted"].value_counts())
print(f"\nReversion rate: {events_df['reverted'].mean() * 100:.1f}%")

print(f"\nAmong reverted events, average days to revert: "
      f"{events_df['days_to_revert'].mean():.1f}")

print("\nSample of labeled events:")
print(events_df[["entry_zscore", "rolling_correlation", "days_since_crossing",
                  "reverted", "days_to_revert"]].head(15))

# ---------------------------------------------------------
# Visualize: spread with reverted events (green) vs broke-down events (red)
# ---------------------------------------------------------

fig, ax = plt.subplots(figsize=(12, 5))
ax.plot(features.index, features["zscore"], color="lightgray", linewidth=0.8, zorder=1)
ax.axhline(ENTRY_THRESHOLD, color="black", linestyle=":", alpha=0.5)
ax.axhline(-ENTRY_THRESHOLD, color="black", linestyle=":", alpha=0.5)

reverted_events = events_df[events_df["reverted"] == 1]
broke_events = events_df[events_df["reverted"] == 0]

ax.scatter(reverted_events.index, reverted_events["entry_zscore"],
           color="green", label=f"Reverted (n={len(reverted_events)})", zorder=2, s=40)
ax.scatter(broke_events.index, broke_events["entry_zscore"],
           color="red", label=f"Broke down (n={len(broke_events)})", zorder=2, s=40)

ax.set_title("JPM/BAC divergence events: reverted vs broke down")
ax.legend()
plt.tight_layout()
plt.savefig("jpm_bac_labeled_events.png", dpi=120)
print("\nSaved plot to jpm_bac_labeled_events.png")
plt.show()

