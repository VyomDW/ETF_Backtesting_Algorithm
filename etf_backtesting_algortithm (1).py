"""
STEP 5b: Walk-forward validation.

One fixed train/test split can be misleading -- if the test period happens
to behave differently than training (which we just saw: 45.5% vs 65.7%
reversion rate), a single split can make a genuinely OK model look bad,
or a genuinely bad model look good, purely by luck of where the cutoff fell.

Walk-forward validation fixes this: we slide the train/test boundary forward
through time in multiple steps, retraining each time, and average performance
across all the folds. This gives a much more honest estimate of whether the
model generalizes, and how much its performance varies across time periods.

Run this locally: pip install pandas numpy scikit-learn matplotlib
"""

import pandas as pd
import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score
import matplotlib.pyplot as plt

print("Loading pooled labeled events...")
