"""
STEP 3 UPGRADE: Kalman Filter dynamic hedge ratio + Ornstein-Uhlenbeck half-life.

Demonstrated on JPM/BAC, but written as reusable functions so you can apply
this to any pair (or loop it across your pooled universe later).

PART A: Kalman Filter dynamic beta
  Old approach: spread = log(JPM) - log(BAC)  (assumes a fixed 1:1 relationship)
  New approach: spread = log(JPM) - beta_t * log(BAC), where beta_t is
  re-estimated every single day using a Kalman filter. This lets the
  hedge ratio adapt as the real relationship between the two stocks drifts.

  Intuition: at each timestep, the Kalman filter keeps a running "best guess"
  of beta, plus how confident it is in that guess. When a new price comes in,
  it nudges the guess toward whatever value would have explained today's
  price movement, weighted by how confident vs. uncertain it currently is.
  This is exactly the standard approach used in Ernest Chan's pairs trading
  methodology.

PART B: Ornstein-Uhlenbeck half-life
  Fits the spread to a mean-reverting stochastic process and solves for
  exactly how many days it typically takes to revert halfway back to its
  mean. This replaces our earlier arbitrary LOOKAHEAD_DAYS=20 guess with a
  number derived from the data.

Run this locally: pip install pykalman pandas numpy statsmodels matplotlib
"""

import pandas as pd
import numpy as np
from pykalman import KalmanFilter
import statsmodels.api as sm
import matplotlib.pyplot as plt

print("Loading universe price data...")
prices = pd.read_csv("universe_prices.csv", index_col="Date", parse_dates=True)

TICKER_A, TICKER_B = "JPM", "BAC"

log_a = np.log(prices[TICKER_A])
log_b = np.log(prices[TICKER_B])


# ---------------------------------------------------------
# PART A: Kalman Filter dynamic hedge ratio
# ---------------------------------------------------------

def kalman_dynamic_beta(y, x, delta=1e-5):
    """
    Estimates a time-varying hedge ratio beta_t such that y_t ~ alpha_t + beta_t * x_t.

    y, x: the two log-price series (y = dependent, x = independent)
    delta: controls how quickly beta is allowed to drift day to day.
           Smaller delta = beta changes more slowly (more stable, less reactive).
           Larger delta = beta adapts faster (more reactive, noisier).

    Returns: DataFrame with columns [alpha, beta] indexed the same as y/x.
    """
    n = len(y)

    # State: [alpha_t, beta_t] -- the intercept and slope, both allowed to
    # drift over time following a random walk (this is what makes them "dynamic")
    trans_cov = delta / (1 - delta) * np.eye(2)

    # Observation matrix changes every timestep: it's [1, x_t], because
    # our model is y_t = alpha_t * 1 + beta_t * x_t
    obs_matrices = np.array([[1, x.iloc[t]] for t in range(n)])[:, np.newaxis, :]

    kf = KalmanFilter(
        n_dim_obs=1,
        n_dim_state=2,
        initial_state_mean=[0, 1],           # start assuming alpha=0, beta=1
        initial_state_covariance=np.ones((2, 2)),
        transition_matrices=np.eye(2),        # state evolves as a random walk
        observation_matrices=obs_matrices,
        observation_covariance=1.0,           # assumed noise in price observations
        transition_covariance=trans_cov,
    )

    state_means, _ = kf.filter(y.values)

    result = pd.DataFrame(state_means, index=y.index, columns=["alpha", "beta"])
    return result


print(f"\nRunning Kalman filter for dynamic {TICKER_A}/{TICKER_B} hedge ratio...")
kalman_result = kalman_dynamic_beta(log_a, log_b)

